// Generates dist/sw.js after `vite build`. The service worker precaches the application shell, hashed assets
// and the bundled content (catalogue, ledger, manifest, free packs) so an installed app starts and studies
// offline. API responses are never cached.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

// Optional argument: output directory name (default "dist").
const dist = join(dirname(fileURLToPath(import.meta.url)), '..', process.argv[2] ?? 'dist');
const walk = dir => readdirSync(dir).flatMap(name => { const p = join(dir, name); return statSync(p).isDirectory() ? walk(p) : [p]; });
const files = walk(dist).filter(f => !f.endsWith('.map') && !f.endsWith(`${sep}sw.js`));
const hash = createHash('sha256');
const urls = files.map(f => { hash.update(relative(dist, f)); hash.update(readFileSync(f)); return '/' + relative(dist, f).split(sep).join('/'); }).map(u => (u === '/index.html' ? '/' : u));
const version = hash.digest('hex').slice(0, 16);

const sw = `// Generated by scripts/build-sw.mjs. Do not edit.
const CACHE = 'caiib-shell-${version}';
const PRECACHE = ${JSON.stringify(urls)};
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('caiib-shell-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
// ignoreVary: module scripts are requested with an Origin header that the precached copy did not have.
const fromCache = async request => (await caches.open(CACHE)).match(request, { ignoreVary: true });
const networkFirst = async (request, fallbackUrl) => {
  try {
    const response = await fetch(request);
    if (response.ok) (await caches.open(CACHE)).put(fallbackUrl || request, response.clone());
    return response;
  } catch (err) {
    const cached = await (await caches.open(CACHE)).match(fallbackUrl || request, { ignoreVary: true });
    if (cached) return cached;
    throw err;
  }
};
self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || url.pathname.startsWith('/api/')) return; // never cache the API
  if (request.mode === 'navigate') { event.respondWith(networkFirst(request, '/')); return; }
  if (url.pathname.startsWith('/content/')) { event.respondWith(networkFirst(request)); return; } // fresh when online, cached when offline
  event.respondWith(fromCache(request).then(hit => hit || fetch(request)));
});
`;
writeFileSync(join(dist, 'sw.js'), sw);
console.log(`service worker: ${urls.length} files precached (cache ${version})`);
